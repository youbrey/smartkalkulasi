def _parse_tiket():
    rows, asal = [], None
    for line in _TIKET_RAW.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("@"):
            asal = line[1:]
            continue
        tujuan, bisnis, ekonomi = line.rsplit(None, 2)
        rows.append((asal, tujuan, int(bisnis), int(ekonomi)))
    return rows


TIKET_PESAWAT = _parse_tiket()          # 316 rute, sesuai Tabel 2.2
KOTA_TIKET = sorted({r[0] for r in TIKET_PESAWAT} | {r[1] for r in TIKET_PESAWAT})


def plafon_tiket(kota_a, kota_b):
    """Cari plafon tiket PP (bisnis, ekonomi) untuk dua kota, dua arah. None jika tidak diatur."""
    a, b = kota_a.strip().upper(), kota_b.strip().upper()
    for asal, tujuan, bis, eko in TIKET_PESAWAT:
        if (asal == a and tujuan == b) or (asal == b and tujuan == a):
            return bis, eko
    return None
